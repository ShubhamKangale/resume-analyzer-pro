-- ============================================================
-- AI Resume Analyzer - Database Schema (MySQL 8.x)
-- ============================================================

CREATE DATABASE IF NOT EXISTS resume_analyzer
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE resume_analyzer;

-- ------------------------------------------------------------
-- USERS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id        INT AUTO_INCREMENT PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role           ENUM('user', 'admin') NOT NULL DEFAULT 'user',
    email_verified TINYINT(1) NOT NULL DEFAULT 0,
    created_at     DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- RESUMES
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS resumes (
    resume_id       INT AUTO_INCREMENT PRIMARY KEY,
    user_id         INT NOT NULL,
    file_name       VARCHAR(255) NOT NULL,
    file_path       VARCHAR(255) NOT NULL,
    extracted_text  LONGTEXT,
    uploaded_at     DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- JOB DESCRIPTIONS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS job_descriptions (
    jd_id       INT AUTO_INCREMENT PRIMARY KEY,
    user_id     INT NOT NULL,
    jd_title    VARCHAR(150),
    jd_text     LONGTEXT NOT NULL,
    created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- SKILLS MASTER (keyword bank used for matching)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS skills_master (
    skill_id    INT AUTO_INCREMENT PRIMARY KEY,
    skill_name  VARCHAR(100) NOT NULL UNIQUE,
    category    VARCHAR(50) DEFAULT 'General'
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- ANALYSIS RESULTS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS analysis_results (
    result_id       INT AUTO_INCREMENT PRIMARY KEY,
    resume_id       INT NOT NULL,
    jd_id           INT NOT NULL,
    match_score     FLOAT NOT NULL,
    matched_skills  TEXT,
    missing_skills  TEXT,
    suggestions     TEXT,
    analyzed_at     DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE,
    FOREIGN KEY (jd_id) REFERENCES job_descriptions(jd_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- AI FEATURE RESULTS (cache so we don't re-call the LLM every click)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai_feature_results (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    result_id   INT NOT NULL,
    feature     VARCHAR(40) NOT NULL,
    output_json LONGTEXT NOT NULL,
    created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_result_feature (result_id, feature),
    FOREIGN KEY (result_id) REFERENCES analysis_results(result_id) ON DELETE CASCADE
) ENGINE=InnoDB;

